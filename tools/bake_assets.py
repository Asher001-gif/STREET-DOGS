"""Bake assets/ models into js/assets.js (plain data) so the game runs from file:// with no loaders.
Run:  python3 tools/bake_assets.py"""
import json, struct, base64, os, sys
import numpy as np
sys.path.insert(0, os.path.dirname(__file__))
import fbx_read
ROOT = os.path.join(os.path.dirname(__file__), '..')
A = lambda *p: os.path.join(ROOT, 'assets', *p)

def glb(name):
    d = open(A('models', name + '.glb'), 'rb').read()
    jl = struct.unpack('<I', d[12:16])[0]; j = json.loads(d[20:20 + jl])
    bo = 20 + jl + 8; bin_ = d[bo:]
    def acc(i):
        a = j['accessors'][i]; bv = j['bufferViews'][a['bufferView']]
        n = {'SCALAR': 1, 'VEC2': 2, 'VEC3': 3}[a['type']]
        dt = {5126: '<f4', 5123: '<u2', 5125: '<u4'}[a['componentType']]
        o = bv.get('byteOffset', 0) + a.get('byteOffset', 0)
        return np.frombuffer(bin_, dtype=dt, count=a['count'] * n, offset=o).reshape(-1, n)
    pr = j['meshes'][0]['primitives'][0]
    return acc(pr['attributes']['POSITION']), acc(pr['attributes']['TEXCOORD_0']), acc(pr['indices']).reshape(-1)

def tex(name):
    return 'data:image/png;base64,' + base64.b64encode(open(A('textures', name), 'rb').read()).decode()

def pack(pos, uv, idx, texture, ground=True):
    mn, mx = pos.min(0), pos.max(0)
    pos = pos - np.array([(mn[0] + mx[0]) / 2, mn[1], (mn[2] + mx[2]) / 2])
    size = (mx - mn).tolist()
    r = lambda a, n: [round(float(x), n) for x in a.reshape(-1)]
    return {'p': r(pos, 3), 'uv': r(uv, 3), 'i': [int(x) for x in idx], 'size': [round(s, 3) for s in size], 'tex': texture}

out = {}
for n, t in [('chair', 'chair128x128.png'), ('vase', 'vase128x128.png'), ('shelf', 'shelf256x256.png'),
             ('couch', 'couch256x256.png'), ('fridge', 'fridge256x256.png'), ('mattress', 'mattress256x256.png')]:
    p, uv, i = glb(n)
    uv = uv.copy()                       # glTF uv origin is top-left; three.js flipY texture expects bottom-left
    uv[:, 1] = 1 - uv[:, 1]
    out[n] = pack(p, uv, i, tex(t))

# dog: FBX is Z-up, faces +Y. Convert to Y-up facing +Z (proper rotation: x,y,z -> -x,z,y)
_, p, u = fbx_read.meshes(A('models', 'dog.fbx'))[0]
p = np.stack([-p[:, 0], p[:, 2], p[:, 1]], 1)
out['dog'] = pack(p, u, np.arange(len(p)), tex('dog.png'))

js = '/* GENERATED by tools/bake_assets.py - do not edit */\nconst ASSETS = ' + json.dumps(out, separators=(',', ':')) + ';\n'
open(os.path.join(ROOT, 'js', 'assets.js'), 'w').write(js)
for k, v in out.items(): print(k, 'verts', len(v['p']) // 3, 'size', v['size'])
print('assets.js KB', len(js) // 1024)
